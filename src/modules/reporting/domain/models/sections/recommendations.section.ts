/**
 * RecommendationPriority indicates urgency.
 */
export enum RecommendationPriority {
  HIGH = 'HIGH',
  MEDIUM = 'MEDIUM',
  LOW = 'LOW',
}

/**
 * RecommendationCategory groups recommendations by concern area.
 */
export enum RecommendationCategory {
  RISK = 'RISK',
  PERFORMANCE = 'PERFORMANCE',
  EXECUTION = 'EXECUTION',
  EXPOSURE = 'EXPOSURE',
}

/**
 * Recommendation — a single actionable insight derived from report metrics.
 *
 * message   — human-readable recommendation in plain English
 * dataPoint — supporting metric: e.g. "Sharpe: 0.23 (below 1.0 threshold)"
 */
export interface Recommendation {
  readonly priority: RecommendationPriority;
  readonly category: RecommendationCategory;
  readonly message: string;
  readonly dataPoint: string;
}

/**
 * RecommendationsSection — automated insights based on metric thresholds.
 *
 * Generated by the RecommendationsBuilder by applying rule-based checks
 * to the other sections of the report. Rules are threshold-based:
 *   e.g. Sharpe < 1.0 → "Consider reducing position size or improving entry filters."
 *
 * riskAlerts — subset of HIGH-priority RISK recommendations, formatted as
 *              short alert strings for dashboard display.
 */
export interface RecommendationsSection {
  readonly items: Recommendation[];
  readonly riskAlerts: string[];
  readonly totalItems: number;
  readonly highPriorityCount: number;
  readonly mediumPriorityCount: number;
  readonly lowPriorityCount: number;
}
