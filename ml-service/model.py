"""
model.py — XGBoost model wrapper.

Responsibilities:
  - Load the trained model artifact from disk on startup (lazy — the sidecar
    starts even if models/signal_classifier.json does not exist yet).
  - Expose predict() that returns a confidence score and signal recommendation.
  - Report whether the model is loaded and its version string.

Model artifact: models/signal_classifier.json
  Generated by train.py.  Baked into the container via a volume mount so
  retraining does not require an image rebuild.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import xgboost as xgb

from features import dict_to_array

# ──────────────────────────────────────────────────────────────────────────────
# Constants
# ──────────────────────────────────────────────────────────────────────────────

DEFAULT_MODEL_PATH = Path(__file__).parent / "models" / "signal_classifier.json"

# Confidence threshold: signal is 'enter' when probability of a winning trade
# exceeds this value, otherwise 'skip'.
# Override via environment variable ENTER_THRESHOLD (e.g. in docker-compose.dev.yml).
# Default 0.45 — lower than 0.55 to capture the model's ranked wins even when
# predicted probabilities don't exceed 0.55 (common with small training sets).
ENTER_THRESHOLD: float = float(os.getenv("ENTER_THRESHOLD", "0.45"))


class SignalModel:
    """Thin wrapper around an XGBClassifier artifact."""

    def __init__(self, model_path: str | Path = DEFAULT_MODEL_PATH) -> None:
        self._path = Path(model_path)
        self._model: xgb.XGBClassifier | None = None
        self._version: str = "unloaded"
        self._load()

    # ── Public API ────────────────────────────────────────────────────────────

    @property
    def is_loaded(self) -> bool:
        return self._model is not None

    @property
    def model_version(self) -> str:
        return self._version

    def predict(self, feature_dict: dict[str, float]) -> dict:
        """
        Score a single candidate trade.

        Parameters
        ----------
        feature_dict : dict
            Keys matching FEATURE_COLS in features.py.

        Returns
        -------
        dict
            {
              "confidence": float,   # probability of a winning trade (0–1)
              "signal":    str,      # "enter" | "skip"
              "modelVersion": str,
            }
        """
        if self._model is None:
            # Model not trained yet — pass every signal through
            return {"confidence": 0.5, "signal": "enter", "modelVersion": "unloaded"}

        X: np.ndarray = dict_to_array(feature_dict)
        proba: float = float(self._model.predict_proba(X)[0][1])
        signal = "enter" if proba >= ENTER_THRESHOLD else "skip"
        return {"confidence": proba, "signal": signal, "modelVersion": self._version}

    def reload(self) -> bool:
        """Hot-reload the model from disk.  Returns True if successful."""
        self._load()
        return self.is_loaded

    # ── Private ───────────────────────────────────────────────────────────────

    def _load(self) -> None:
        if not self._path.exists():
            # Not an error — the sidecar starts before training is done
            self._model = None
            self._version = "unloaded"
            return
        try:
            clf = xgb.XGBClassifier()
            clf.load_model(str(self._path))
            self._model = clf
            # Encode mtime as version so callers can detect reloads
            mtime = int(os.path.getmtime(self._path))
            self._version = f"v1-{mtime}"
        except Exception as exc:  # noqa: BLE001
            self._model = None
            self._version = f"load-error: {exc}"
