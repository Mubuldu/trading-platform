import { StrategyPermission } from './permissions';

/**
 * PluginAuthor identifies the developer or organization that authored the plugin.
 */
export interface PluginAuthor {
  /** Full legal name or organization name. */
  readonly name: string;
  /** Contact email (recommended for marketplace listings). */
  readonly email?: string;
  /** URL to author's website or profile. */
  readonly url?: string;
}

/**
 * PluginDependency declares an external npm dependency the plugin requires.
 *
 * The platform maintains an allowlist of approved dependencies.
 * Unlisted dependencies cause validation to fail. This prevents supply-chain
 * attacks via undeclared or unpinned packages.
 *
 * version MUST be an exact semver (e.g. "4.17.21", not "^4").
 * Unpinned ranges are rejected to guarantee reproducible plugin builds.
 */
export interface PluginDependency {
  readonly name: string;
  readonly version: string;
}

/**
 * PluginRiskLimits overrides the platform's default risk parameters for this strategy.
 *
 * The platform applies the more conservative of the platform-wide limit and the
 * per-strategy override. A plugin cannot relax platform limits — it can only
 * tighten them. Omitting a field means "use the platform default".
 *
 * maxRuntimeMs        — max wall-clock milliseconds per hook call before timeout
 * maxEventsPerSecond  — rate limit for event dispatches to this strategy
 */
export interface PluginRiskLimits {
  readonly maxPositionSizePercent?: number;
  readonly maxDrawdownPercent?: number;
  readonly maxOpenOrders?: number;
  readonly maxRuntimeMs?: number;
  readonly maxEventsPerSecond?: number;
}

/**
 * PluginManifest is the static self-description of a strategy plugin.
 *
 * Every strategy must provide a manifest. The platform validates it before loading
 * the plugin — a missing or invalid manifest causes immediate rejection.
 *
 * Required field contracts:
 *
 *   id                — lowercase, hyphen-separated, globally unique (e.g. "sma-crossover-v1")
 *   version           — semver (e.g. "1.0.0"); MUST increment on any behavioral change
 *   requiredSdkVersion— semver RANGE (e.g. "^1.0.0"); platform rejects incompatible plugins
 *   permissions       — MUST include GENERATE_SIGNALS; unused permissions SHOULD be omitted
 *   license           — SPDX identifier (e.g. "MIT", "Apache-2.0", "UNLICENSED")
 *
 * Optional field contracts:
 *
 *   dependencies      — each dependency MUST be exact-version pinned and allowlisted
 *   riskLimits        — overrides are clamped; they can only be stricter than platform defaults
 *   keywords          — max 20 keywords, each max 50 chars; used for marketplace search
 *   homepage          — must be HTTPS; used for marketplace metadata only
 */
export interface PluginManifest {
  readonly id: string;
  readonly name: string;
  readonly version: string;
  readonly author: PluginAuthor;
  readonly license: string;
  readonly description: string;
  readonly requiredSdkVersion: string;
  readonly permissions: readonly StrategyPermission[];
  readonly dependencies?: readonly PluginDependency[];
  readonly riskLimits?: PluginRiskLimits;
  readonly homepage?: string;
  readonly keywords?: readonly string[];
}

/**
 * MarketplaceMetadata is generated by the platform from the PluginManifest.
 *
 * This is used for marketplace listing preparation — not the marketplace UI itself.
 * The UI is a separate concern (out of scope for this milestone).
 *
 * installedAt, lastActivatedAt, and usageStats are set by the platform at runtime.
 */
export interface MarketplaceMetadata {
  readonly manifest: PluginManifest;
  readonly installedAt: number;
  readonly lastActivatedAt: number | null;
  readonly isVerified: boolean;
  readonly checksum: string;
  readonly usageStats: {
    readonly totalSignalsGenerated: number;
    readonly totalRuntimeMs: number;
    readonly errorCount: number;
  };
}
